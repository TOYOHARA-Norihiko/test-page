# Perform wavelet coherency analysis between osaka_cli and hyogo_cli
coh_result <- analyze.coherency(cli_data,
                                my.pair = c("osaka_cli", "hyogo_cli"),
                                loess.span = 0,
                                dt = 1,
                                dj = 1/20,
                                lowerPeriod = 2,
                                upperPeriod = 50,
                                make.pval = TRUE,
                                n.sim = 10)

# Plot the result with COI and contour
wt.image(coh_result,
         main = "Wavelet Coherency: Osaka vs Hyogo CLI",
         show.coi = TRUE,
         show.contour = TRUE,
         siglvl = 0.05,
         legend.params = list(lab = "Coherency", lab.cex = 1),
         show.date = FALSE)
